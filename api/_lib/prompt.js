export const LEVEL_RULES = {
  easy: "[답변 길이] 쉬운 설명 모드입니다. 초등학생도 이해할 수 있게 2~4문장으로 짧게 답합니다.",
  detail: "[답변 길이] 자세한 설명 모드입니다. 역사·문화적 배경까지 포함해 4~7문장으로 답합니다.",
};

// AI에게 넘겨줄 전시물 정보. 출처(sources)와 URL은 넘기지 않는다.
const EXHIBIT_FIELDS = [
  ["title", "작품명"],
  ["artist", "작가/제작자"],
  ["chapter", "챕터"],
  ["basicDescription", "기본 설명"],
  ["workInfo", "작품 정보"],
  ["historicalContext", "역사·문화적 배경"],
  ["exhibitionMeaning", "전시에서의 의미"],
  ["additionalInfo", "추가 정보"],
];

// 규칙 + 설명 수준 + 전시물 정보를 하나의 지시문으로 합친다. (Groq 등에서 사용)
export function buildSystemPrompt(exhibit, level) {
  return `${ANSWER_RULES}\n\n${LEVEL_RULES[level] || LEVEL_RULES.easy}\n\n${buildExhibitContext(exhibit)}`;
}

export function buildExhibitContext(exhibit) {
  const lines = EXHIBIT_FIELDS.filter(([key]) => exhibit[key]).map(([key, label]) => `${label}: ${exhibit[key]}`);
  return `<전시물_정보>
전시관: ${exhibit.hall}
${lines.join("\n")}
</전시물_정보>`;
}
